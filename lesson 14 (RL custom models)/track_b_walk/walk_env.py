"""УЧЕБНАЯ среда ходьбы двуногого «ЦАПЛЯ-2» (R4, 33 кг) на MuJoCo.

ЧТО ЭТО
-------
Тонкая, читаемая версия боевой среды `_reference_walk_env_r4.py` (70 КБ,
949 строк, 24 члена награды). Здесь 6 членов награды плюс терминальное
событие падения, эпизод 6 с вместо 20 с, нулевая доменная рандомизация и
только команда «вперёд». Всё выброшенное выброшено НЕ потому, что оно
лишнее в боевом проекте, а потому что на горизонте студента (≤2 ч
обучения) ему не на что действовать — разбор в README, раздел «Что
выброшено и почему».

ГЛАВНОЕ СВОЙСТВО: наблюдение осталось ТЕМ ЖЕ 35-мерным, что у боевой
среды, поэтому эталонная политика 60M грузится и работает прямо здесь.
Студент обучает свою политику и сравнивает её с эталоном в одной системе
координат, без пересчётов. Проверка совпадения наблюдения — `probe.py`.

ЗАМЕРЕННЫЕ ЧИСЛА (модель `tsaplya2.xml`, снято с живого `MjModel`;
источник — отчёт разбора 08_track_b.md, раздел 1, и повторено в probe.py)
-------------------------------------------------------------------------
    масса машины            33.0530 кг
    тел / суставов / приводов   12 / 9 (1 free + 8 шарниров) / 8
    nq / nv                 15 / 14
    шаг физики              0.002 с (500 Гц), FRAME_SKIP 10 -> политика 50 Гц
    высота таза в стойке    z0 = 0.4272 м
    порог падения           0.55*z0 = 0.2350 м
    стопа                   сфера R 24 мм — контакт ТОЧЕЧНЫЙ, голеностопа нет.
                            Пассивно машина стоять не может в принципе.
    ПАССИВНАЯ БАЗА (действие 0, 1g, без рандомизации): 53 шага = 1.06 с
                            (08_track_b.md, раздел 2; повторно меряется probe.py)

ЧЕСТНОЕ ПРЕДУПРЕЖДЕНИЕ ПРО БЮДЖЕТ
---------------------------------
За 30 минут ходьбы не будет. В боевой среде на 6.5 млн шагов средняя
длина эпизода равна РОВНО 53.0 — столько же, сколько у машины с нулевым
действием (`evaluations.npz` прогона r4f, 13 точек от 0.5 до 13.0 млн,
08_track_b.md раздел 5). Перелом — на 13.5 млн шагов ≈ 1 ч 02 мин.
Эта учебная среда за 22 минуты / 1.67 млн шагов подняла длину эпизода
53 -> 68.5 (+29 %), то есть дала НЕплоский график, но не ходьбу
(08_track_b.md, раздел 6, фактический прогон автора отчёта).

Таблица бюджетов — в README.md.

ЧТО ЗДЕСЬ УЧЕБНОГО, КРОМЕ КОРОТКОГО КОДА
----------------------------------------
* награда собрана из `rl_toolkit.rewards.Term` — у каждого члена есть
  поле `why`, и члена без `why` в курсе не бывает;
* `info["terms"]` отдаёт вклад КАЖДОГО члена за шаг — это то, что читают
  `probe_reward_terms`, `RewardLogCallback` и `null_policy_baseline`;
* есть методы куррикулума `set_gravity_scale` / `set_cmd_scale`, есть
  `set_probe_state` для `probe_termination` и `set_cmd_vx` для
  `probe_controller_sweep`.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import gymnasium as gym
import mujoco
import numpy as np

HERE = Path(__file__).resolve().parent
# rl_toolkit лежит на уровень выше — в корне урока
sys.path.insert(0, str(HERE.parent))

from rl_toolkit.rewards import Ctx, RewardRegistry, Term  # noqa: E402

# --------------------------------------------------------------------------
# КОНСТАНТЫ ФИЗИКИ И ЭПИЗОДА
# --------------------------------------------------------------------------

MODEL = "tsaplya2.xml"

# 500 Гц физики / 10 = 50 Гц политики. Взято из боевой среды
# (_reference_walk_env_r4.py:185). 50 Гц — это и частота реального
# контура на железе (CAN + прошивка), менять его без причины нельзя:
# вся калибровка весов награды сделана в единицах «за шаг 0.02 с».
FRAME_SKIP = 10

# ЭПИЗОД 6 с вместо боевых 20 с (_reference_walk_env_r4.py:186).
# Зачем короче (08_track_b.md, раздел 6):
#   (а) ранние эпизоды и так обрываются на 1.06 с — потолок 20 с
#       превращает ep_len_mean в «доля от 1000», где прогресс не виден;
#   (б) быстрее набирается статистика VecNormalize;
#   (в) на порядок чаще показывает политике старт из стойки.
# Плата: длинные горизонты (разгон-торможение) не выучатся. Для урока
# это приемлемо, для боевого проекта — нет.
EP_LEN_S = 6.0

# --- масштабные опоры боевого рецепта (_reference_walk_env_r4.py:203-205) --
# Всё, что зависит от размера машины, пересчитывается от эталонной ноги
# H_REF через число Фруда Fr = v²/(g*h): при сохранении Fr скорость растёт
# как sqrt(h), а частота шага падает как 1/sqrt(h).
H_REF = 0.1445          # эталонная высота таза, м (машина, на которой калибровали)
V_REF = 0.5             # эталонная максимальная команда, м/с
F_PHASE_REF = 1.4       # эталонная частота фазовых часов, Гц

# --------------------------------------------------------------------------
# ВЕСА НАГРАДЫ
# Все шесть весов взяты из боевой среды. Две правки против боевых значений
# сделаны сознательно и подписаны — см. комментарии у W_IDLE и W_ROLL.
# --------------------------------------------------------------------------

W_LIN = 2.2             # _reference_walk_env_r4.py:696 — ядро слежения
W_ALIVE = 0.10          # :711
W_HEIGHT = 0.30         # :710
W_ACT = 0.25            # :724
W_PITCH = 4.0           # :720 (боевое значение)
# ПРАВКА 1. В боевой среде крен наказан в 10 раз дороже тангажа
# (W_ROLL = 40.0, :720) — потому что наверху корпуса стоит ГРУЗ, и качает
# его именно крен. В курсе груза нет, поэтому вес симметричный
# (08_track_b.md, раздел 6: «Оставляем p_tilt, но можно взять
# симметричный вес»). Что НЕЛЬЗЯ трогать — квадратичность ОТ НУЛЯ:
# у прогона r4c была свободная полоса 20°, градиент к вертикали
# занулялся, и 24 млн шагов ушли в аттрактор «медленно валиться вбок».
W_ROLL = 4.0
# ПРАВКА 2. Боевой вес простоя 0.5 (:755). В фактическом прогоне учебной
# среды (08_track_b.md, раздел 6, «что я бы поправил в своём прототипе»,
# пункт 2) при 0.5 средняя награда ушла в -17…-24: награда выродилась в
# «штраф за то, что не идёшь», и градиент к выживанию утонул. Понижено
# вдвое. Второе лекарство оттуда же — растянуть cmd_scale на весь
# бюджет — применено в train.py (командная рампа длиннее гравитационной).
W_IDLE = 0.25
# Штраф падения. Событие, а не член: платится один раз в момент обрыва.
# -10 боевой среде не хватало — «нырок-и-крах» собирал награду за скорость
# до конца эпизода и перевешивал штраф (диагноз r4b,
# _reference_walk_env_r4.py:657-660). Поднято до -50 и в этом виде дожило
# до 60 млн шагов.
W_FALL = 50.0


def _build_registry() -> RewardRegistry:
    """Шесть членов награды плюс терминальное событие падения.

    Каждый член — ЧИСТАЯ функция от снимка состояния `Ctx`. Это не
    украшение: только чистую функцию можно прогнать через
    `diagnostics.sweep_term` на синтетическом состоянии с заранее
    известным ответом и спросить «а есть ли тут вообще градиент».
    В боевой среде члены лезут в `self.data`, и проверить их так нельзя.
    """
    reg = RewardRegistry()

    # 1 -----------------------------------------------------------------
    def f_lin(c: Ctx) -> float:
        # ОТНОСИТЕЛЬНОЕ ядро слежения: ширина привязана к величине команды.
        sigma = max(0.35 * c["cmd_mag"], 0.07)
        err2 = (c["vx"] - c["cmd_x"]) ** 2 + c["vy"] ** 2
        return math.exp(-err2 / (2.0 * sigma ** 2))

    reg.add(Term(
        name="r_lin", fn=f_lin, weight=W_LIN, unit="доля",
        why=("Ядро слежения за командой скорости. Ширина ОТНОСИТЕЛЬНАЯ, "
             "sigma = max(0.35*|cmd|, 0.07). Абсолютное ядро exp(-8*err^2) "
             "платит неподвижной машине 28 % награды при команде 0.4 м/с — "
             "это аттрактор «стоять выгоднее», на котором соседняя ветка "
             "проекта сожгла пять версий (_reference_walk_env_r4.py:682-691). "
             "Относительное платит стоянию ~1.7 % при ЛЮБОЙ команде. "
             "Ядро менять нельзя."),
    ))

    # 2 -----------------------------------------------------------------
    def f_idle(c: Ctx) -> float:
        if c["cmd_mag"] < 0.05:
            return 0.0          # команды нет — простоя нет по определению
        return -max(0.0, 1.0 - max(c["v_along"], 0.0) / c["cmd_mag"])

    reg.add(Term(
        name="p_idle", fn=f_idle, weight=W_IDLE, unit="доля",
        # Гейт — множитель куррикулума: пока команды малы, давление
        # «двигайся» не должно выдёргивать машину из-под баланса.
        gate=lambda c: float(c["cmd_scale"]),
        why=("ЛИНЕЙНЫЙ штраф простоя под ненулевой командой. Без него "
             "экспоненциальное ядро r_lin делает стояние выгоднее ходьбы "
             "(головной докстринг боевой среды, строки 10-11). Один "
             "множитель, но именно он превращает «не падать» в «идти». "
             "Вес понижен 0.5 -> 0.25 по замеру учебного прогона: при 0.5 "
             "суммарная награда уходит в минус и топит градиент выживания."),
    ))

    # 3 -----------------------------------------------------------------
    reg.add(Term(
        name="r_alive", fn=lambda c: 1.0, weight=W_ALIVE, unit="1",
        why=("Плата за то, что эпизод ещё идёт. Без неё ранние эпизоды "
             "длиной 1 с дают отрицательный возврат, и политика честно "
             "учится падать БЫСТРЕЕ — чтобы меньше платить."),
    ))

    # 4 -----------------------------------------------------------------
    def f_tilt(c: Ctx) -> float:
        return -(W_PITCH * c["g0"] ** 2 + W_ROLL * c["g1"] ** 2)

    reg.add(Term(
        name="p_tilt", fn=f_tilt, weight=1.0, unit="g^2",
        why=("Квадратичный штраф наклона ОТ НУЛЯ (веса вшиты в fn, потому "
             "что их два — тангаж и крен). Свободная полоса вокруг "
             "вертикали недопустима: у прогона r4c полоса 20 градусов "
             "занулила градиент у вертикали, и 24 млн шагов ушли в "
             "аттрактор «медленно валиться вбок» — выживание 1.4 с при "
             "пассивных 1.1 с (_reference_walk_env_r4.py:713-716)."),
    ))

    # 5 -----------------------------------------------------------------
    def f_height(c: Ctx) -> float:
        return math.exp(-c["k_height"] * (c["h_trunk"] - c["z0"]) ** 2)

    reg.add(Term(
        name="r_height", fn=f_height, weight=W_HEIGHT, unit="доля",
        why=("Держать таз на высоте стойки z0. Без этого члена дешёвое "
             "решение — присесть в «раскоряку» и не падать: точечная стопа "
             "R 24 мм позволяет расставить ноги очень широко. Жёсткость "
             "ядра k_height = 200*(H_REF/z0)^2 пересчитывается под рост "
             "машины, а не задаётся руками."),
    ))

    # 6 -----------------------------------------------------------------
    reg.add(Term(
        name="p_act", fn=lambda c: -float(c["a2"]), weight=W_ACT, unit="a^2",
        why=("Штраф величины действия. Гасит насыщенные режимы-аттракторы "
             "и честен для железа (плавные малые команды). В норме ходьбы "
             "(|a| ~ 0.2…0.5) стоит единицы процентов награды слежения. "
             "Единственный «инженерный» штраф, который оставлен: на "
             "горизонте урока он заменяет p_rate/p_jerk/p_energy боевой "
             "среды по эффекту (08_track_b.md, раздел 6)."),
    ))

    # событие -----------------------------------------------------------
    reg.add(Term(
        name="p_fall", fn=lambda c: -1.0 if c["fallen"] else 0.0,
        weight=W_FALL, unit="событие",
        why=("ТЕРМИНАЛЬНОЕ СОБЫТИЕ, а не член: платится один раз в момент "
             "обрыва. Держит цену падения выше выгоды от рывка (~110/с): "
             "при -10 «нырок-и-крах» собирал награду за скорость до конца "
             "эпизода и оставался выгодным (диагноз r4b, "
             "_reference_walk_env_r4.py:657-660)."),
    ))
    return reg


class WalkEnv(gym.Env):
    """Учебная среда ходьбы. Плоский пол, команда только вперёд, 6 с эпизод.

    Наблюдение (35) — ПОБИТОВО тот же формат, что у боевой среды
    (_reference_walk_env_r4.py:413, 474-501):

        [ 0: 3]  вектор гравитации в раме корпуса (безразмерный, |g| = 1)
        [ 3: 6]  гироскоп * 0.25          (рад/с, масштабирован)
        [ 6:14]  углы 8 суставов          (рад)
        [14:22]  скорости суставов * 0.05 (рад/с, масштабированы)
        [22:30]  предыдущее действие      (-1…1)
        [30:33]  команда [vx, vy, wz]     (в учебной версии vy = wz = 0)
        [33:35]  фазовые часы [sin, cos]

    Действие (8) — нормированные уставки положения приводов, -1…1.
    """

    metadata = {"render_modes": ["rgb_array"], "render_fps": 50}

    def __init__(self, seed: int | None = None, render_mode: str | None = None,
                 model: str = MODEL):
        self.model = mujoco.MjModel.from_xml_path(str(HERE / model))
        self.data = mujoco.MjData(self.model)
        self.render_mode = render_mode
        self._renderer = None
        self.rng = np.random.default_rng(seed)

        self.nu = self.model.nu
        self.dt = self.model.opt.timestep * FRAME_SKIP      # 0.02 с = 50 Гц
        self.max_steps = int(EP_LEN_S / self.dt)            # 300 шагов

        # z0 читается ИЗ МОДЕЛИ, а не пишется числом: поменяли XML —
        # пересчиталось всё остальное. Головной докстринг боевой среды в
        # этом месте устарел (там 0.326 при фактических 0.4272), поэтому
        # правило простое: числа берём из объекта, не из текста.
        self.z0 = float(self.model.qpos0[2])
        self.ctrl_lo = self.model.actuator_ctrlrange[:, 0].copy()
        self.ctrl_hi = self.model.actuator_ctrlrange[:, 1].copy()
        # действие -1…1 отображается в ЧЕТВЕРТЬ хода привода. Полный ход
        # 33-килограммовой машине не нужен, а разведка с полным ходом её
        # мгновенно ломает.
        self.act_scale = 0.25 * (self.ctrl_hi - self.ctrl_lo)

        # масштабные пересчёты по числу Фруда
        k = math.sqrt(self.z0 / H_REF)
        self.v_cmd_max = V_REF * k          # 0.8597 м/с при z0 = 0.4272
        self.f_phase = F_PHASE_REF / k      # 0.8142 Гц
        self.k_height = 200.0 * (H_REF / self.z0) ** 2   # 22.882
        self.z_fall = 0.55 * self.z0        # 0.2350 м

        self.obs_dim = 3 + 3 + 3 * self.nu + 3 + 2       # = 35
        self.observation_space = gym.spaces.Box(-np.inf, np.inf,
                                                (self.obs_dim,), np.float32)
        self.action_space = gym.spaces.Box(-1.0, 1.0, (self.nu,), np.float32)

        # куррикулум: 0.35g -> 1g и 0 -> 1 по командам. Ведёт тренер через
        # set_gravity_scale / set_cmd_scale (см. train.py).
        self.g_scale = 1.0
        self.cmd_scale = 1.0
        # фиксированная команда для проб и оценки; None — розыгрыш
        self._cmd_vx_fixed: float | None = None

        self.reward = _build_registry()
        self.reset()

    # ------------------------------------------------------------------
    # наблюдение
    # ------------------------------------------------------------------
    def _gravity_body(self) -> np.ndarray:
        """Вектор гравитации в раме корпуса. Это ЕДИНСТВЕННЫЙ канал, по
        которому политика узнаёт свой наклон: абсолютной ориентации в
        наблюдении нет и быть не должно (на железе её тоже нет — там
        акселерометр и гироскоп)."""
        R = np.zeros(9)
        mujoco.mju_quat2Mat(R, self.data.qpos[3:7])
        return R.reshape(3, 3).T @ np.array([0.0, 0.0, -1.0])

    def _obs(self) -> np.ndarray:
        g = self._gravity_body()
        gyro = self.data.qvel[3:6].copy()
        qj = self.data.qpos[7:7 + self.nu].copy()
        vj = self.data.qvel[6:6 + self.nu].copy()
        phase = np.array([math.sin(self._phase), math.cos(self._phase)])
        # ВАЖНО: prev_act — действие ПРЕДЫДУЩЕГО шага. Именно оно сейчас
        # доехало до приводов (в step стоит задержка на шаг), поэтому в
        # наблюдении оно, а не то, что политика выдала только что.
        cmd = np.array([self.cmd[0], self.cmd[1], self.cmd[2]])
        obs = np.concatenate([g, gyro * 0.25, qj, vj * 0.05,
                              self.prev_act, cmd, phase])
        return obs.astype(np.float32)

    # ------------------------------------------------------------------
    def reset(self, *, seed=None, options=None):
        if seed is not None:
            self.rng = np.random.default_rng(seed)
        mujoco.mj_resetData(self.model, self.data)

        # НУЛЕВАЯ РАНДОМИЗАЦИЯ. В боевой среде здесь 11 источников
        # случайности: массы ±15 %, трение ×0.5…1.25, позы N(0, 0.03),
        # шум наблюдений, толчок 0.2…0.5 м/с, зеркало, 60 % команд назад.
        # Всё это делает задачу ТРУДНЕЕ, а не легче, и на горизонте урока
        # только мешает: в журнале проекта свип с рандомизацией дал 1-2
        # падения из 3 назад там, где без неё их не было
        # (08_track_b.md, раздел 6).
        if self._cmd_vx_fixed is not None:
            # ЗАФИКСИРОВАННАЯ команда куррикулумом НЕ масштабируется: её
            # ставят для оценки и свипов, и «0.4, но на самом деле 0.1»
            # сделало бы любую такую таблицу враньём.
            vx_cmd = float(self._cmd_vx_fixed)
        else:
            if self.rng.random() < 0.25:
                vx = 0.0    # четверть эпизодов — «стой на месте»
            else:
                vx = float(self.rng.uniform(0.0, self.v_cmd_max))
            vx_cmd = vx * self.cmd_scale
        # Команда только ВПЕРЁД и без поворота: боковая составляющая и
        # угловая скорость выброшены вместе с контуром курса.
        self.cmd = np.array([vx_cmd, 0.0, 0.0])

        self.prev_act = np.zeros(self.nu)
        self._delayed = np.zeros(self.nu)
        self._act_filt = np.zeros(self.nu)
        # Фаза стартует случайно: политика обязана уметь идти с любой
        # фазы, а не только из постоянного нуля.
        self._phase = float(self.rng.uniform(0.0, 2.0 * math.pi))
        # частота фазовых часов: каденс = |v_cmd| / длина шага, но не ниже
        # базовой f_phase (при команде 0 это марш на месте 0.81 Гц)
        d_swing = min(0.35, max(0.15, 0.6 * abs(float(self.cmd[0]))
                                      / self.f_phase))
        self._f_eff = max(self.f_phase, abs(float(self.cmd[0])) / d_swing)
        self.steps = 0
        self.reward.reset()
        mujoco.mj_forward(self.model, self.data)
        return self._obs(), {}

    # ------------------------------------------------------------------
    # методы куррикулума и проб
    # ------------------------------------------------------------------
    def set_gravity_scale(self, scale: float) -> None:
        """Гравитационный куррикулум 0.35g -> 1g. Применяется НЕМЕДЛЕННО.

        Зачем: при 1g пассивная машина живёт 1.06 с, при 0.35g — 1.80 с
        (08_track_b.md, раздел 2). Полуторакратный запас времени и есть
        то окно, в котором бутстрап value-функции успевает замкнуться.
        """
        self.g_scale = float(scale)
        self.model.opt.gravity[2] = -9.81 * self.g_scale

    def set_cmd_scale(self, scale: float) -> None:
        """Командный куррикулум 0 -> 1. Применяется со СЛЕДУЮЩЕГО эпизода
        (команда разыгрывается в reset), а вот гейт члена p_idle читает
        его сразу — и это правильно: давление «двигайся» обязано расти
        синхронно с самой командой."""
        self.cmd_scale = float(scale)

    def set_cmd_vx(self, vx: float | None) -> None:
        """Зафиксировать продольную команду (для оценки и свипов).
        None — вернуться к розыгрышу. Имя вида set_<param> — контракт
        `probes.probe_controller_sweep`."""
        self._cmd_vx_fixed = None if vx is None else float(vx)

    def set_probe_state(self, state: dict) -> None:
        """Поставить машину в заданную позу — контракт `probe_termination`.

        Ключи: `z` (высота таза, м), `pitch`, `roll` (рад). Всё остальное
        из стойки. Нужен, чтобы проверить условие обрыва НЕ ожиданием
        случайного падения, а прямым выставлением состояния.
        """
        mujoco.mj_resetData(self.model, self.data)
        if "z" in state:
            self.data.qpos[2] = float(state["z"])
        pitch = float(state.get("pitch", 0.0))
        roll = float(state.get("roll", 0.0))
        if pitch or roll:
            # кватернион из углов Эйлера (крен вокруг X, тангаж вокруг Y)
            cr, sr = math.cos(roll / 2), math.sin(roll / 2)
            cp, sp = math.cos(pitch / 2), math.sin(pitch / 2)
            self.data.qpos[3:7] = [cr * cp, sr * cp, cr * sp, -sr * sp]
        mujoco.mj_forward(self.model, self.data)

    # ------------------------------------------------------------------
    def step(self, action):
        action = np.clip(np.asarray(action, dtype=np.float64), -1.0, 1.0)

        # ЗАДЕРЖКА НА ШАГ + ЕМА-ФИЛЬТР. Две строки, которые оставлены из
        # боевой среды без изменений (_reference_walk_env_r4.py:610-616):
        # на железе между решением политики и движением привода стоят CAN
        # и прошивка (~10…20 мс = ровно шаг), а alpha = 0.7 даёт срез
        # ~19 Гц. Более узкая полоса (alpha 0.4, срез 5 Гц) съедала
        # балансный запас: у 33-кг машины постоянная времени падения
        # ~220 мс.
        self._act_filt = 0.3 * self._act_filt + 0.7 * self._delayed
        self.data.ctrl[:] = np.clip(self._act_filt * self.act_scale,
                                    self.ctrl_lo, self.ctrl_hi)
        self._delayed = action.copy()

        for _ in range(FRAME_SKIP):
            mujoco.mj_step(self.model, self.data)
        self.steps += 1
        self._phase = (self._phase + 2.0 * math.pi * self._f_eff
                       * self.dt) % (2.0 * math.pi)

        obs = self._obs()

        # --- состояние для награды ------------------------------------
        q, v = self.data.qpos, self.data.qvel
        g = self._gravity_body()
        quat = q[3:7]
        yaw = math.atan2(2 * (quat[0] * quat[3] + quat[1] * quat[2]),
                         1 - 2 * (quat[2] ** 2 + quat[3] ** 2))
        c, s = math.cos(-yaw), math.sin(-yaw)
        vx = c * v[0] - s * v[1]        # скорость в горизонтальной раме корпуса
        vy = s * v[0] + c * v[1]

        # ПАДЕНИЕ определяется ДО награды, чтобы штраф падения был обычным
        # членом реестра, а не приписанным сбоку числом. Наклон > 45°
        # (g[2] > -cos45) считается падением сразу, не дожидаясь касания
        # корпусом пола: иначе «нырок-и-крах» успевает собрать награду за
        # скорость до конца эпизода.
        z = float(q[2])
        fallen = bool(z < self.z_fall or g[2] > -0.7071)

        cmd_mag = abs(float(self.cmd[0]))
        v_along = vx * float(np.sign(self.cmd[0])) if cmd_mag > 0 else 0.0
        ctx = Ctx(
            dt=self.dt, t=self.steps * self.dt,
            vx=vx, vy=vy, cmd_x=float(self.cmd[0]), cmd_mag=cmd_mag,
            v_along=v_along, cmd_scale=self.cmd_scale,
            g0=float(g[0]), g1=float(g[1]), g2=float(g[2]),
            h_trunk=z, z0=self.z0, k_height=self.k_height,
            a2=float(np.sum(action ** 2)), fallen=fallen,
        )
        r, terms = self.reward(ctx)

        self.prev_act = action.copy()
        truncated = self.steps >= self.max_steps
        return obs, r, fallen, truncated, {"terms": terms}

    # ------------------------------------------------------------------
    def render(self):
        if self.render_mode != "rgb_array":
            return None
        if self._renderer is None:
            self._renderer = mujoco.Renderer(self.model, 480, 640)
        self._renderer.update_scene(self.data)
        return self._renderer.render()

    def close(self):
        if self._renderer is not None:
            self._renderer.close()
            self._renderer = None


def make_env(rank: int = 0, seed: int = 0):
    """Фабрика для SubprocVecEnv/DummyVecEnv. Разные сиды на разные среды —
    иначе восемь копий проживут восемь одинаковых эпизодов."""
    def _thunk():
        env = WalkEnv(seed=seed + rank)
        return env
    return _thunk


