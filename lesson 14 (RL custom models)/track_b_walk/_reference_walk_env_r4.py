# ЗАМЫКАНИЕ КУРСА В УПРАВЛЕНИИ (r4u). ШТРАФА МАЛО: в наблюдении политики
# ошибки курса НЕТ вовсе. Там гравитация в СК корпуса (это только крен и
# тангаж, вокруг вертикали она инвариантна), гироскоп (МГНОВЕННАЯ скорость,
# не накопленный угол), позы, скорости, prev_act, команда и фаза. То есть
# r4t штрафует накопленный увод, который политика физически не наблюдает, —
# уменьшать его она может только вслепую, симметрией походки. Ровно так это
# и выглядит на приёмке: за 7 млн шагов путь 2.56 → 2.41, падения 18 → 25,
# профиль по дорожкам сплющился в полосу вместо роста.
#
# Лечение — не новый штраф, а ОБРАТНАЯ СВЯЗЬ. Канал для неё уже есть:
# командная угловая скорость cmd[2] лежит в наблюдении, и следовать ей
# политика умеет (r_ang). Поэтому вместо сырой команды на вход подаётся
#     wz_eff = clip(cmd_wz − K·yaw_err, ±WZ_MAX),
# где yaw_err — накопленная ошибка против опорного курса. Опора продолжает
# интегрировать ИСХОДНУЮ команду, а не wz_eff: иначе опора поехала бы за
# машиной и контур выродился бы в тождество.
#
# Что это даёт бесплатно: контур работает и с УЖЕ ОБУЧЕННЫМИ весами, без
# хирургии над сетью и без изменения размерности наблюдения (35). Значит
# его можно проверить ЗАМЕРОМ ДО обучения — как того требует правило,
# оплаченное прогоном r4p.
#
# K = 0 полностью воспроизводит поведение r4t.
# K ЗАМЕРЕН, а не назначен: свип на готовых весах r4t 200.0M, 8 эпизодов по
# 20 с, команда вперёд 0.5 м/с, модель tsaplya2.xml (sim/_probe_yaw_loop.py):
#     K=0.0  увод 112.3°  снос 5.39 м  вперёд 5.50 м   <- поведение r4t
#     K=1.6  увод  40.3°  снос 2.82 м  вперёд 8.27 м
#     K=2.0  увод  39.2°  снос 2.57 м  вперёд 8.40 м   <- взят
#     K=2.6  увод  39.7°  снос 2.68 м  вперёд 8.46 м
# Плато 1.6…2.6 — значит выбор не на краю и не требует точной подгонки.
# Падений во всех режимах 0/8, то есть подруливание не разбалансирует машину.
CTRL_YAW_K = 2.0        # 1/с; на ошибке 10° даёт 0.35 рад/с подруливания
CTRL_WZ_MAX = 0.6       # тот же потолок, что у розыгрыша команд
# ПОТОЛОК САМОЙ ПОПРАВКИ, отдельно от потолка команды. Без него контур
# ВРЕДИТ на рельефе. Механизм: после толчка о препятствие ошибка курса
# скачком велика, контур требует подруливания под ±0.6 рад/с, а yaw — самый
# слабый привод машины (DM-J8009, 30.1 Н·м против 112.9 на бедре), и попытка
# развернуться прямо в момент постановки стопы валит машину. Выпрямление
# курса в установившемся режиме требует долей рад/с, всплеск не нужен.
#
# СВИП ПОТОЛКА (готовые веса r4t 200.0M; ровно — 8 эпизодов по 20 с,
# полигон — 8 дорожек × 6 эпизодов):
#     потолок   увод      снос     полигон   падений из 48
#     нет (K=0) 112.3°    5.39 м   2.47 м    18      <- поведение r4t
#     ±0.25      74.0°    4.06 м   2.96 м    19
#     ±0.40      55.9°    3.39 м   2.73 м    20      <- взят
#     ±0.60      39.2°    2.57 м   2.13 м    25
# Размен монотонный: больше поправка — прямее курс, хуже рельеф. Взят 0.40:
# прямизна и есть цель прогона, а полигон при ней всё ещё выше базы r4t.
# ЗАПАСНОЙ ВАРИАНТ, если рельеф в прогоне просядет: 0.25 — единственная
# точка, которая лучше базы СРАЗУ по обеим осям.
CTRL_WZ_CORR_MAX = 0.40

# Порог засчёта полёта опущен 0.05 → 0.03 с: на 0.05 нога успевала
