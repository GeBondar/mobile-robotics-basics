# Опорный курс ИНТЕГРИРУЕТ командный wz, поэтому член работает одинаково и
# для «прямо» (опора стоит), и для «поворот» (опора едет с нужной скоростью).
# Ошибка заворачивается в ±π, значит штраф ограничен W_YAW·π² и не может
# взорваться при падении с раскруткой.
# Вес подобран ЗАМЕРОМ, а не на глаз: при 0.5 член давал −105.5/с против
# r_lin +84.5/с и задавил бы всё остальное (полная награда падала с ~700
